def _allocate_axis(
    ceiling: int | None,
    verification_ppm: int | None,
    evidence_ppm: int | None,
    rollback_ppm: int | None,
) -> dict[str, Any]:
    if ceiling is None:
        return {
            "ceiling": None,
            "verification_reserve": None,
            "evidence_reserve": None,
            "rollback_reserve": None,
            "section_allocations": {section: None for section in RESOURCE_SECTIONS},
        }
    if not all(type(value) is int for value in (verification_ppm, evidence_ppm, rollback_ppm)):
        raise CuratorContractError("known budget lacks reserve percentages")
    verification_rate = cast(int, verification_ppm)
    evidence_rate = cast(int, evidence_ppm)
    rollback_rate = cast(int, rollback_ppm)
    verification = max(1, ceiling * verification_rate // 1_000_000)
    evidence = max(1, ceiling * evidence_rate // 1_000_000)
    rollback = max(1, ceiling * rollback_rate // 1_000_000)
    remaining = ceiling - verification - evidence - rollback
    if remaining < len(RESOURCE_SECTIONS):
        raise CuratorContractError("known budget cannot fund all Curator sections")
    base, remainder = divmod(remaining, len(RESOURCE_SECTIONS))
    allocations = {
        section: base + (1 if index < remainder else 0)
        for index, section in enumerate(RESOURCE_SECTIONS)
    }
    return {
        "ceiling": ceiling,
        "verification_reserve": verification,
        "evidence_reserve": evidence,
        "rollback_reserve": rollback,
        "section_allocations": allocations,
    }


def _resource_accounting(request: Mapping[str, Any]) -> dict[str, Any]:
    state = _budget_state(request)
    return {
        "accounting_status": state,
        "lease_status": "not-issued",
        "axes": {
            axis: _allocate_axis(
                request["budgets"][axis],
                request["verification_reserve_ppm"],
                request["evidence_reserve_ppm"],
                request["rollback_reserve_ppm"],
            )
            for axis in RESOURCE_AXES
        },
        "budget_authorized": False,
    }


def compile_curator_verification(request: Mapping[str, Any]) -> dict[str, Any]:
    copied = _validated_request(request)
    successor = compile_curator_successor()
    request_digest = digest(copied)
    resource = _resource_accounting(copied)
    outputs = {
        "verification_scope": _verification_scope(copied, request_digest),
        "claim_reconstruction": _claim_reconstruction(copied, request_digest),
        "clean_boundary_reproduction": _clean_boundary_reproduction(copied, request_digest),
        "counterexample_search": _counterexample_search(copied, request_digest),
        "security_privacy_review": _security_privacy_review(copied, request_digest),
        "provenance_license_review": _provenance_license_review(copied, request_digest),
        "regression_analysis": _regression_analysis(copied, request_digest),
        "artifact_receipt_verification": _artifact_receipt_verification(copied, request_digest),
        "rollback_verification": _rollback_verification(copied, request_digest),
        "release_recommendation": _release_recommendation(copied, request_digest),
        "dissent_unresolved_evidence": _dissent_unresolved_evidence(copied, request_digest),
    }
    body = {
        "record_type": "curator-verification-envelope",
        "schema_version": 1,
        "request_id": copied["request_id"],
        "objective_id": copied["objective_id"],
        "tenant_id": copied["tenant_id"],
        "repository_id": copied["repository_id"],
        "successor_digest": successor["content_digest"],
        "request_digest": request_digest,
        "request_snapshot": deepcopy(copied),
        "outputs": outputs,
        "resource_accounting": resource,
        "activation": "inert",
        "authority": "none",
        "public": False,
    }
    envelope = {**body, "verification_digest": digest(body)}
    validation = validate_curator(
        "curator-verification-envelope-v1",
        envelope,
        enforce_canonical_envelope=False,
    )
    if not validation.valid:
        raise CuratorContractError(
            "generated Curator verification is invalid: " + "; ".join(validation.issues)
        )
    return deepcopy(envelope)


def curator_verification_bytes(request: Mapping[str, Any]) -> bytes:
    return canonical_bytes(compile_curator_verification(request))


