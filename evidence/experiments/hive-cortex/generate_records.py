"""Regenerate the retained EVAL-520 demonstration evaluation records.

Run from anywhere; the script pins the working directory to the repository root
so every retained artifact reference is a repository-relative POSIX path.

    PYTHONPATH=src python evidence/experiments/hive-cortex/generate_records.py

The run is idempotent: identical inputs produce identical evaluation ids and
identical canonical bytes, so re-running validates the retained records instead
of rewriting them (append-only retention).
"""

from __future__ import annotations

import os
import sys
from hashlib import sha256
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPOSITORY_ROOT / "src"))
os.chdir(REPOSITORY_ROOT)

from hive_mind_os.brain_kernel.canonical import canonical_bytes, canonical_digest
from hive_mind_os.brain_kernel.evaluation_runtime import (
    ChallengerDescriptor,
    EvaluationIdentities,
    EvaluationRuntime,
    SealedHoldout,
    SurfaceKind,
    SurfaceResult,
)

EVIDENCE_ROOT = Path("evidence/experiments/hive-cortex")
ARTIFACT_ROOT = EVIDENCE_ROOT / "_artifacts"

IDENTITIES = EvaluationIdentities(
    "optimizer:challenger-proposer",
    "builder:isolated-workspace",
    "curator:independent-evaluator",
)
DESCRIPTOR = ChallengerDescriptor(
    "challenger:hive-cortex-eval-520-demo",
    "champion:hive-cortex-baseline",
    "refs/heads/autopilot/eval-520",
    canonical_digest({"demonstration": "EVAL-520", "challenger": 1}),
)
HOLDOUT_CASES = {
    "case-preserve-evidence": {"expected": "retain losing benchmark", "weight": 2},
    "case-repair-regression": {"expected": "revert and re-measure", "weight": 1},
}
KEEP_SAMPLES = {
    SurfaceKind.HELD_OUT: ((0.50, 0.52, 0.48), (0.80, 0.82, 0.78)),
    SurfaceKind.PIT: ((0.60, 0.61, 0.59), (0.66, 0.67, 0.65)),
    SurfaceKind.ADVERSARIAL: ((0.90, 0.90, 0.90), (0.91, 0.90, 0.91)),
    SurfaceKind.COMPARATOR: ((0.70, 0.70, 0.70), (0.72, 0.71, 0.73)),
}
MISSING_ARTIFACT_BYTES = b'{"surface":"held-out","note":"never retained"}\n'


def _retain_artifact(name: str, document: dict[str, object]) -> str:
    path = ARTIFACT_ROOT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = canonical_bytes(document) + b"\n"
    if path.is_file():
        if path.read_bytes() != payload:
            raise SystemExit(f"retained demonstration artifact was mutated: {name}")
    else:
        path.write_bytes(payload)
    return f"{path.as_posix()}#sha256:{sha256(payload).hexdigest()}"


def _surface(kind: SurfaceKind, reference: str | None = None) -> SurfaceResult:
    baseline, candidate = KEEP_SAMPLES[kind]
    if reference is None:
        reference = _retain_artifact(
            f"{kind.value}.json",
            {
                "surface": kind.value,
                "baseline_samples": list(baseline),
                "candidate_samples": list(candidate),
            },
        )
    return SurfaceResult(kind, f"{kind.value}-surface", baseline, candidate, (reference,))


def main() -> None:
    runtime = EvaluationRuntime()

    keep_holdout = SealedHoldout("holdout:eval-520-demo", HOLDOUT_CASES)
    keep_seal = keep_holdout.seal_prediction(
        IDENTITIES.evaluator_id, {"expected_verdict": "unknown-before-reveal"}
    )
    keep_holdout.reveal(keep_seal)
    keep = runtime.evaluate(
        DESCRIPTOR,
        IDENTITIES,
        [_surface(kind) for kind in SurfaceKind],
        keep_holdout,
        evidence_root=EVIDENCE_ROOT,
    )

    quarantine_holdout = SealedHoldout("holdout:eval-520-demo", HOLDOUT_CASES)
    quarantine_seal = quarantine_holdout.seal_prediction(
        IDENTITIES.evaluator_id, {"expected_verdict": "unknown-before-reveal"}
    )
    quarantine_holdout.reveal(quarantine_seal)
    missing_reference = (
        f"{(ARTIFACT_ROOT / 'held-out-unretained.json').as_posix()}"
        f"#sha256:{sha256(MISSING_ARTIFACT_BYTES).hexdigest()}"
    )
    quarantine = runtime.evaluate(
        DESCRIPTOR,
        IDENTITIES,
        [
            _surface(SurfaceKind.HELD_OUT, missing_reference),
            *(_surface(kind) for kind in SurfaceKind if kind is not SurfaceKind.HELD_OUT),
        ],
        quarantine_holdout,
        evidence_root=EVIDENCE_ROOT,
    )

    readme = EVIDENCE_ROOT / "README.md"
    lines = [
        "# hive-cortex evaluation receipts (EVAL-520)",
        "",
        "Machine-generated by the independent evaluation runtime",
        "(`hive_mind_os.brain_kernel.evaluation_runtime.EvaluationRuntime.evaluate`).",
        "Nothing here is hand-authored output; regenerate with:",
        "",
        "```",
        "PYTHONPATH=src python evidence/experiments/hive-cortex/generate_records.py",
        "```",
        "",
        "Retention is append-only and deterministic: identical inputs yield the same",
        "`evaluation_id` and the same canonical bytes, so a re-run verifies the",
        "retained records rather than rewriting them.",
        "",
        "| record | verdict | reasons | record digest |",
        "|---|---|---|---|",
    ]
    for record in (keep, quarantine):
        lines.append(
            f"| `{record.evaluation_id}.json` | `{record.verdict.value}` | "
            f"{'; '.join(record.reasons)} | `{record.record_digest}` |"
        )
    lines += [
        "",
        "- The `keep` record demonstrates AC1/AC2/AC3: independent evaluator identity,",
        "  a holdout revealed only after its prediction seal, repeated measurements on",
        "  all four surfaces, and a held-out effect above the measured noise floor.",
        "- The `quarantine` record demonstrates AC4: its held-out surface references an",
        "  artifact that was deliberately never retained, so the evaluation quarantines",
        "  instead of retesting optimistically. Losing evidence is retained in full.",
        "- `_artifacts/` holds the surface logs referenced by the `keep` record;",
        "  `_artifacts/held-out-unretained.json` is intentionally absent.",
        "",
    ]
    readme.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    print(f"{keep.evaluation_id} {keep.verdict.value} {keep.record_digest}")
    print(f"{quarantine.evaluation_id} {quarantine.verdict.value} {quarantine.record_digest}")


if __name__ == "__main__":
    main()
