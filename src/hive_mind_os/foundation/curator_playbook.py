def curator_successor_bytes() -> bytes:
    return canonical_bytes(compile_curator_successor())


def _strict_json_copy(
    value: Any,
    *,
    path: str = "$",
    depth: int = 0,
    counter: list[int] | None = None,
) -> Any:
    if counter is None:
        counter = [0]
    counter[0] += 1
    if counter[0] > MAX_NESTED_VALUES:
        raise CuratorContractError("request exceeds bounded nested-value limit")
    if depth > 24:
        raise CuratorContractError("request exceeds bounded nesting depth")
    if value is None or type(value) in {bool, int}:
        return value
    if type(value) is float:
        if not math.isfinite(value):
            raise CuratorContractError(f"{path} contains a non-finite number")
        return value
    if type(value) is str:
        if len(value) > MAX_TEXT:
            raise CuratorContractError(f"{path} exceeds bounded text limit")
        return value
    if type(value) is list:
        return [
            _strict_json_copy(item, path=f"{path}[{index}]", depth=depth + 1, counter=counter)
            for index, item in enumerate(value)
        ]
    if type(value) is dict:
        copied: dict[str, Any] = {}
        for key, item in value.items():
            if type(key) is not str:
                raise CuratorContractError(f"{path} contains a non-string key")
            copied[key] = _strict_json_copy(
                item,
                path=f"{path}.{key}",
                depth=depth + 1,
                counter=counter,
            )
        return copied
    raise CuratorContractError(f"{path} contains unsupported type {type(value).__name__}")


def _unique_ids(values: list[Mapping[str, Any]], field: str, label: str) -> list[str]:
    identifiers = [str(item[field]) for item in values]
    if len(identifiers) != len(set(identifiers)):
        raise CuratorContractError(f"duplicate {label} identifier")
    return identifiers


def _require_subset(values: list[str], admitted: set[str], label: str) -> None:
    unknown = sorted(set(values) - admitted)
    if unknown:
        raise CuratorContractError(f"{label} references unknown identifiers: {', '.join(unknown)}")


def _current_fingerprint(request: Mapping[str, Any]) -> str:
    return digest(
        {
            "objective_id": request["objective_id"],
            "subject_commit": request["subject_commit"],
            "subject_tree": request["subject_tree"],
            "claims": [
                {
                    "claim_id": item["claim_id"],
                    "claim_type": item["claim_type"],
                    "evidence": sorted(item["builder_evidence_refs"]),
                }
                for item in sorted(request["claims"], key=lambda item: item["claim_id"])
            ],
            "checks": [
                {
                    "check_id": item["check_id"],
                    "command": item["command"],
                    "expected": item["expected"],
                }
                for item in sorted(request["sealed_checks"], key=lambda item: item["check_id"])
            ],
        }
    )


def _normalized_builder_envelope(value: Mapping[str, Any]) -> dict[str, Any]:
    normalized = deepcopy(value)
    outputs = normalized.get("outputs")
    if isinstance(outputs, Mapping):
        normalized["outputs"] = {
            field: deepcopy(outputs[field])
            for field in BUILDER_OUTPUT_FIELDS
            if field in outputs
        }
    return normalized


def _validate_request_semantics(request: dict[str, Any]) -> None:
    try:
        reject_private_content(request)
    except ValueError as error:
        raise CuratorContractError(str(error)) from error

    builder = _normalized_builder_envelope(request["builder_envelope"])
    builder_validation = validate_builder("builder-implementation-envelope-v1", builder)
    if not builder_validation.valid:
        raise CuratorContractError(
            "Builder envelope is invalid: " + "; ".join(builder_validation.issues)
        )
    if (
        builder["tenant_id"] != request["tenant_id"]
        or builder["repository_id"] != request["repository_id"]
    ):
        raise CuratorContractError("Builder envelope scope differs from Curator request")
    builder_scope = builder["request_snapshot"]["scope"]
    if (
        builder_scope["subject_commit"] != request["subject_commit"]
        or builder_scope["subject_tree"] != request["subject_tree"]
    ):
        raise CuratorContractError("Builder subject differs from Curator request")
    handoff = builder["outputs"]["curator_handoff"]
    if (
        handoff["next_role"] != "curator"
        or handoff["independent_reconstruction_required"] is not True
    ):
        raise CuratorContractError("Builder did not produce the required Curator handoff")

    builder_identity = request["builder_identity"]
    curator_identity = request["curator_identity"]
    if builder_identity["role"] != "builder" or curator_identity["role"] != "curator":
        raise CuratorContractError("verification identities have incorrect roles")
    if builder_identity["actor_id"] == curator_identity["actor_id"]:
        raise CuratorContractError("Curator cannot verify the Builder under the same identity")
    if request["blind_seal_sequence"] >= request["candidate_access_sequence"]:
        raise CuratorContractError("blind verification checks were not sealed before candidate access")

    acceptance_ids = set(_unique_ids(request["acceptance_criteria"], "acceptance_id", "acceptance"))
    claims = request["claims"]
    claim_ids = set(_unique_ids(claims, "claim_id", "claim"))
    checks = request["sealed_checks"]
    _unique_ids(checks, "check_id", "sealed check")
    evidence = request["observed_evidence"]
    evidence_ids = set(_unique_ids(evidence, "evidence_id", "evidence"))
    sources = request["sources"]
    source_ids = set(_unique_ids(sources, "source_id", "source"))
    targets = request["regression_targets"]
    _unique_ids(targets, "target_id", "regression target")

    for claim in claims:
        _require_subset(claim["acceptance_refs"], acceptance_ids, f"claim {claim['claim_id']} acceptance")
        _require_subset(claim["builder_evidence_refs"], evidence_ids, f"claim {claim['claim_id']} evidence")
        _require_subset(claim["source_refs"], source_ids, f"claim {claim['claim_id']} sources")
    covered_acceptance = {ref for claim in claims for ref in claim["acceptance_refs"]}
    if covered_acceptance != acceptance_ids:
        raise CuratorContractError("claims do not cover every acceptance criterion")

    for check in checks:
        _require_subset(check["claim_refs"], claim_ids, f"check {check['check_id']} claims")
        _require_subset(check["acceptance_refs"], acceptance_ids, f"check {check['check_id']} acceptance")
        if check["sealed_before_candidate_access"] is not True:
            raise CuratorContractError("unsealed check cannot become verification evidence")
    checked_claims = {ref for check in checks for ref in check["claim_refs"]}
    if checked_claims != claim_ids:
        raise CuratorContractError("sealed checks do not cover every material claim")

    required_receipt_fields = {
        "command",
        "exit_code",
        "started_at",
        "finished_at",
        "stdout_digest",
        "stderr_digest",
        "subject_commit",
        "subject_tree",
    }
    for item in evidence:
        _require_subset(item["claim_refs"], claim_ids, f"evidence {item['evidence_id']} claims")
        _require_subset(item["acceptance_refs"], acceptance_ids, f"evidence {item['evidence_id']} acceptance")
        if item["integrity_status"] != "digest-verified":
            raise CuratorContractError(f"evidence {item['evidence_id']} is forged or unverifiable")
        if item["stale"] is not False:
            raise CuratorContractError(f"evidence {item['evidence_id']} is stale")
        if item["subject_commit"] not in {request["base_commit"], request["subject_commit"]}:
            raise CuratorContractError(f"evidence {item['evidence_id']} leaks a future or foreign commit")
        if item["subject_tree"] not in {request["base_tree"], request["subject_tree"]}:
            raise CuratorContractError(f"evidence {item['evidence_id']} has a foreign tree")
        if item["kind"] in {"test-before", "test-after", "security", "privacy", "rollback"}:
            if item["producer_role"] == "builder":
                raise CuratorContractError(
                    f"evidence {item['evidence_id']} is Builder self-verification"
                )
            if not required_receipt_fields.issubset(set(item["receipt_fields"])):
                raise CuratorContractError(
                    f"evidence {item['evidence_id']} lacks complete receipt fields"
                )
    covered_evidence = {ref for claim in claims for ref in claim["builder_evidence_refs"]}
    if not covered_evidence.issubset(evidence_ids):
        raise CuratorContractError("claims reference unavailable evidence")

    material_claim_ids = {claim["claim_id"] for claim in claims if claim["material"]}
    for source in sources:
        _require_subset(source["claim_refs"], claim_ids, f"source {source['source_id']} claims")
        if material_claim_ids.intersection(source["claim_refs"]):
            if source["license_status"] != "admitted" or source["completeness"] != "complete":
                raise CuratorContractError(
                    f"source {source['source_id']} cannot support material claims"
                )
    sourced_material = {
        ref
        for source in sources
        if source["license_status"] == "admitted" and source["completeness"] == "complete"
        for ref in source["claim_refs"]
    }
    if not material_claim_ids.issubset(sourced_material):
        raise CuratorContractError("material claims have source or license gaps")

    for target in targets:
        if target["assertions_after"] < target["assertions_before"]:
            raise CuratorContractError(f"regression target {target['target_id']} weakens assertions")
        if target["test_functions_after"] < target["test_functions_before"]:
            raise CuratorContractError(f"regression target {target['target_id']} removes tests")

    point_in_time = request["point_in_time"]
    if point_in_time["target_commit"] != request["subject_commit"]:
        raise CuratorContractError("point-in-time target differs from subject commit")
    if point_in_time["knowledge_cutoff_commit"] not in {
        request["base_commit"],
        request["subject_commit"],
    }:
        raise CuratorContractError("point-in-time knowledge cutoff is foreign")
    if point_in_time["future_commit_refs"]:
        raise CuratorContractError("future commit knowledge is prohibited")

    actor_roles = [item["role"] for item in request["actors"]]
    actor_ids = [item["actor_id"] for item in request["actors"]]
    if tuple(actor_roles) != COURT_ROLES:
        raise CuratorContractError("procedural role catalog is incomplete or reordered")
    if len(actor_ids) != len(set(actor_ids)):
        raise CuratorContractError("procedural actor identifiers must be unique")
    if any(item["authenticated"] is not False for item in request["actors"]):
        raise CuratorContractError("caller cannot manufacture authenticated actors")

    budget_values = list(request["budgets"].values())
    reserves = [
        request["verification_reserve_ppm"],
        request["evidence_reserve_ppm"],
        request["rollback_reserve_ppm"],
    ]
    known = all(type(value) is int for value in budget_values)
    unknown = all(value is None for value in budget_values)
    if not (known or unknown):
        raise CuratorContractError("resource axes must be wholly known or wholly unknown")
    if known:
        if not all(type(value) is int and value > 0 for value in reserves):
            raise CuratorContractError("known resources require positive reserves")
        if sum(cast(int, value) for value in reserves) >= 1_000_000:
            raise CuratorContractError("resource reserves consume the full budget")
    elif any(value is not None for value in reserves):
        raise CuratorContractError("unknown resources cannot manufacture reserves")

    if any(value is not False for value in request["caller_claims"].values()):
        raise CuratorContractError("caller cannot assert completion, passing tests, release, or independence")
    current = _current_fingerprint(request)
    if current in request["prior_fingerprints"]:
        raise CuratorContractError("verification request repeats a prior semantic fingerprint")


def _validated_request(request: Mapping[str, Any]) -> dict[str, Any]:
    if type(request) is not dict:
        raise CuratorContractError("Curator request must be an exact built-in object")
    copied = _strict_json_copy(request)
    validation = validate_curator("curator-verification-request-v1", copied)
    if not validation.valid:
        raise CuratorContractError("Curator request is invalid: " + "; ".join(validation.issues))
    _validate_request_semantics(copied)
    return copied


def _budget_state(request: Mapping[str, Any]) -> str:
    return "known" if all(type(value) is int for value in request["budgets"].values()) else "unknown"


